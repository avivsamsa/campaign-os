/**
 * שלד ברירת המחדל ל-brand_md שנטען בעת יצירת לקוח חדש (פאזה 1).
 * שם הלקוח מוזרק לכותרת; אם ריק — נשאר ה-placeholder.
 */
export function makeBrandSkeleton(name: string): string {
  const display = name.trim() || '[שם הלקוח]';
  return `# ${display} — Brand Brief
## קהל יעד
- מי הלקוח האידיאלי, גיל, מאפיינים, מיקום
## שפה ואיך מדברים
- טון, גוף פנייה, מילים שכן / לא משתמשים
## ההצעה
- מה מוכרים, חבילות, טווחי מחיר
## בידול
- למה אצלנו ולא אצל המתחרים
## שפה מיתוגית
- ערכים, אווירה, סגנון ויזואלי
## Do / Don't
- מה תמיד / מה לעולם לא בתקשורת השיווקית`;
}
